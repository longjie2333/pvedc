import { test, expect } from '@playwright/test';
import { generateSync } from 'otplib';

test('administrator login, roster, network, profiles and responsive settings', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '管理员入口' }).click();
  await page.getByLabel('动态验证码').fill(generateSync({ secret: 'JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP' }));
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '计算资源总览' })).toBeVisible();
  await page.getByRole('link', { name: '学生名单', exact: true }).click();
  await page.getByRole('button', { name: '添加学生' }).click();
  await page.getByLabel('学号', { exact: true }).fill('00990001');
  await page.getByLabel('姓名', { exact: true }).fill('本地测试同学');
  await page.getByLabel('班级', { exact: true }).fill('集成测试班');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByText('本地测试同学', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '导入名单' }).click();
  await page.getByLabel('学生名单 CSV').fill('学号,姓名,班级\n00990002,批量测试同学,集成测试班');
  await page.getByRole('button', { name: '导入', exact: true }).click();
  await expect(page.getByText('批量测试同学', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: '网络与地址池', exact: true }).click();
  await page.getByRole('button', { name: '添加配置' }).click();
  await page.getByLabel('网络名称').fill('仅本地测试网络');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('heading', { name: '仅本地测试网络' })).toBeVisible();
  await page.getByRole('link', { name: '资源配置', exact: true }).click();
  await page.getByRole('button', { name: '添加配置' }).click();
  await page.getByLabel('配置名称').fill('仅本地测试规格');
  await page.getByRole('switch', { name: '公开发布' }).check();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('heading', { name: '仅本地测试规格' })).toBeVisible();
  await page.getByRole('button', { name: '设为默认' }).click();
  await expect(page.getByText('默认配置', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/admin-profiles.png', fullPage: true });
  await page.getByRole('link', { name: '平台设置', exact: true }).click();
  await expect(page.getByRole('heading', { name: '站点与分配策略' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile-settings.png', fullPage: true });
  expect(errors).toEqual([]);
});
